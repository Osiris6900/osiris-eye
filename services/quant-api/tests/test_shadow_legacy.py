"""Read real v1 shadow evidence without changing its original bodies or seals.

The fixture was generated by the unmodified shadow.py at commit c196eab4 under
a fresh 28-digit Decimal context, then read back by that historical code. It is
static so compatibility checks do not regenerate evidence with today's engine.
"""

import copy
import json
from decimal import ROUND_UP, Context, Inexact, Rounded, localcontext
from pathlib import Path

import pytest

from osiris_api.control_plane.database import Database, digest
from osiris_api.control_plane.shadow import COMPARISONS, RUNS, ShadowService

FIXTURE = Path(__file__).parent / "fixtures" / "shadow_v1_394.json"
RUN_SHA256 = "3129909cbe4c292b421ac8f676a0d95bac239eff758c5ed90d6126921f02e60d"
COMPARISON_SHA256 = "ff839a5512f15b81f1780a40ca73bb078296caac594cf9e544ada238ad08fee6"


@pytest.fixture
def legacy(tmp_path):
    evidence = json.loads(FIXTURE.read_text())
    db = Database(str(tmp_path / "legacy.db"))
    db.put(RUNS, "legacy-run", evidence["run"])
    db.put(COMPARISONS, "legacy-comparison", evidence["comparison"])
    return db, ShadowService(db), evidence


def strict_context(precision):
    context = Context(prec=precision, rounding=ROUND_UP)
    context.traps[Inexact] = True
    context.traps[Rounded] = True
    return context


def test_fixture_retains_historical_source_and_original_seals(legacy):
    _, _, evidence = legacy
    assert evidence["source_commit"] == "c196eab4a2f3cc3bf4bdda2070b213b90d537dcd"
    assert evidence["decimal_precision"] == 28
    assert evidence["run"]["policy"] == "lagged-long-flat-independent-risk-v1"
    assert evidence["comparison"]["policy"] == "event-aligned-paper-equity-v1"
    assert evidence["run"]["shadow_run_sha256"] == RUN_SHA256
    assert evidence["comparison"]["comparison_sha256"] == COMPARISON_SHA256
    for body, seal in (
        (evidence["run"], "shadow_run_sha256"),
        (evidence["comparison"], "comparison_sha256"),
    ):
        assert digest({key: value for key, value in body.items() if key != seal}) == body[seal]


@pytest.mark.parametrize("precision", [6, 50])
def test_v1_run_and_comparison_reads_and_replays_preserve_exact_evidence(legacy, precision):
    db, service, evidence = legacy
    original_run = db.get(RUNS, "legacy-run")
    original_comparison = db.get(COMPARISONS, "legacy-comparison")
    equivalent_ticks = copy.deepcopy(evidence["ticks"])
    equivalent_ticks[0]["price"] = "100.000"
    with localcontext(strict_context(precision)):
        assert service.get_run("legacy-run") == evidence["run"]
        assert service.run("legacy-run", evidence["ticks"]) == evidence["run"]
        assert service.run("legacy-run", equivalent_ticks) == evidence["run"]
        assert service.get_comparison("legacy-comparison") == evidence["comparison"]
        assert service.create_comparison("legacy-comparison", "alice", evidence["request"]) == {
            "comparison": evidence["comparison"],
            "replayed": True,
            "live_execution": False,
        }
        aligned = service.compare("legacy-run", evidence["run"]["equity"])
        assert aligned["max_absolute_difference"] == "0"
        assert aligned["execution_authorized"] is False
    assert db.get(RUNS, "legacy-run") == original_run
    assert db.get(COMPARISONS, "legacy-comparison") == original_comparison


@pytest.mark.parametrize("creation_precision", [6, 50])
def test_new_v2_comparison_can_bind_unchanged_v1_run_across_strict_contexts(
    legacy,
    creation_precision,
):
    db, service, evidence = legacy
    original_run = db.get(RUNS, "legacy-run")
    with localcontext(strict_context(creation_precision)):
        created = service.create_comparison("v2-from-legacy", "alice", evidence["request"])
    report = created["comparison"]
    assert created["replayed"] is False
    assert report["policy"] == "event-aligned-paper-equity-v2"
    assert report["shadow_run_sha256"] == RUN_SHA256
    assert report["final_difference"] == "-25"
    assert report["max_absolute_difference"] == "25"
    for precision in (6, 50):
        with localcontext(strict_context(precision)):
            assert service.get_comparison("v2-from-legacy") == report
            assert service.create_comparison("v2-from-legacy", "alice", evidence["request"]) == {
                "comparison": report,
                "replayed": True,
                "live_execution": False,
            }
            assert service.get_run("legacy-run") == evidence["run"]
    assert db.get(RUNS, "legacy-run") == original_run
    assert db.get(COMPARISONS, "v2-from-legacy") == {"version": 1, "value": report}


@pytest.mark.parametrize("precision", [6, 50])
def test_v1_ids_still_reject_changed_inputs_without_replacing_evidence(legacy, precision):
    db, service, evidence = legacy
    changed_ticks = copy.deepcopy(evidence["ticks"])
    changed_ticks[0]["price"] = "101"
    formerly_aliased_ticks = copy.deepcopy(evidence["ticks"])
    formerly_aliased_ticks[0]["price"] = "100.000000000000000000000000001"
    changed_request = copy.deepcopy(evidence["request"])
    changed_request["paper_observations"][-1]["equity"] = "10081"
    with localcontext(strict_context(precision)):
        with pytest.raises(ValueError, match="^shadow_run_id_conflict$"):
            service.run("legacy-run", changed_ticks)
        with pytest.raises(ValueError, match="^shadow_run_id_conflict$"):
            service.run("legacy-run", formerly_aliased_ticks)
        with pytest.raises(ValueError, match="^shadow_run_id_conflict$"):
            service.run("legacy-run", evidence["ticks"], fee_bps="11")
        with pytest.raises(ValueError, match="^shadow_comparison_id_conflict$"):
            service.create_comparison("legacy-comparison", "alice", changed_request)
        with pytest.raises(ValueError, match="^shadow_comparison_id_conflict$"):
            service.create_comparison("legacy-comparison", "bob", evidence["request"])
    assert db.get(RUNS, "legacy-run") == {"version": 1, "value": evidence["run"]}
    assert db.get(COMPARISONS, "legacy-comparison") == {
        "version": 1,
        "value": evidence["comparison"],
    }


@pytest.mark.parametrize("precision", [6, 50])
@pytest.mark.parametrize("kind", ["run", "comparison"])
@pytest.mark.parametrize("reseal", [False, True])
def test_corrupted_v1_evidence_is_rejected_by_reads_and_replays(
    legacy,
    precision,
    kind,
    reseal,
):
    db, service, evidence = legacy
    body = copy.deepcopy(evidence[kind])
    if kind == "run":
        collection, key, seal = RUNS, "legacy-run", "shadow_run_sha256"
        body["pnl"] = "0"
        label = "shadow_run"
    else:
        collection, key, seal = COMPARISONS, "legacy-comparison", "comparison_sha256"
        body["paper_pnl"] = "0"
        label = "shadow_comparison"
    if reseal:
        body[seal] = digest({field: value for field, value in body.items() if field != seal})
        error = f"invalid_{label}"
    else:
        error = f"{label}_digest_mismatch"
    db.put(collection, key, body, expected_version=1)
    with localcontext(strict_context(precision)):
        with pytest.raises(ValueError, match=f"^{error}$"):
            if kind == "run":
                service.get_run(key)
            else:
                service.get_comparison(key)
        with pytest.raises(ValueError, match=f"^{error}$"):
            if kind == "run":
                service.run(key, evidence["ticks"])
            else:
                service.create_comparison(key, "alice", evidence["request"])
    assert db.get(collection, key) == {"version": 2, "value": body}
