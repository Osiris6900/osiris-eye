#!/usr/bin/env python3
"""Shared parser for the hashed Python deployment lock.

The lock file (`services/quant-api/requirements-lock.txt`) is the supported
resolved deployment environment for the quant API. It is generated by
`scripts/resolve_python_lock.py` (pip-tools, backtracking resolver) and every
distribution entry must be exactly pinned (`name==version`) and carry at
least one `--hash=sha256:` artifact digest. The parser fails closed: any
content line that is not a pinned, hashed requirement is an error, so a
hand-edited or partially generated lock can never be treated as resolved.

This is dependency-resolution evidence, not a vulnerability scan, a license
review, or proof that the resolved set is free of defects.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re

LOCK_RELATIVE_PATH = "services/quant-api/requirements-lock.txt"
LOCK_HEADER_SCHEMA = "osiris.python-deployment-lock.v1"

_REQ_RE = re.compile(
    r"\A(?P<name>[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)"
    r"(?:\[[A-Za-z0-9._, -]*\])?"
    r"==(?P<version>[A-Za-z0-9][A-Za-z0-9.!+_]*)"
    r"(?P<marker>\s*;\s*\S.*)?\Z"
)
_HASH_TOKEN_RE = re.compile(r"--hash=sha256:(?P<digest>[0-9a-f]{64})(?=\s|\Z)")
_HEADER_RE = re.compile(r"\A#\s*(?P<key>[a-z0-9_]+):\s*(?P<value>.+?)\s*\Z")


def normalize_name(name: str) -> str:
    """PEP 503 normalization so `Foo_Bar` and `foo-bar` compare equal."""
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass(frozen=True)
class LockedRequirement:
    name: str
    version: str
    hashes: tuple[str, ...]
    marker: str | None = None

    @property
    def normalized_name(self) -> str:
        return normalize_name(self.name)


def _logical_lines(text: str) -> list[tuple[int, str]]:
    """Join backslash continuations into (first_line_number, content) pairs."""
    logical: list[tuple[int, str]] = []
    pending: list[str] = []
    pending_start = 0
    for number, raw in enumerate(text.splitlines(), start=1):
        stripped = raw.strip()
        if not pending and (not stripped or stripped.startswith("#")):
            continue
        if not pending:
            pending_start = number
        if stripped.endswith("\\"):
            pending.append(stripped[:-1].strip())
            continue
        pending.append(stripped)
        logical.append((pending_start, " ".join(part for part in pending if part)))
        pending = []
    if pending:
        raise ValueError(f"lock file ends inside a continuation started at line {pending_start}")
    return logical


def parse_hashed_lock(path: Path) -> list[LockedRequirement]:
    """Parse the hashed lock, rejecting anything that is not pinned+hashed.

    Extras markers (`uvicorn[standard]==...`) are accepted and stripped: the
    locked distribution is the base package and pip-compile keeps the marker
    only to document why the package was resolved.
    """
    entries: list[LockedRequirement] = []
    seen: dict[str, int] = {}
    for number, content in _logical_lines(path.read_text()):
        hashes = _HASH_TOKEN_RE.findall(content)
        residual = _HASH_TOKEN_RE.sub("", content).strip()
        if "--hash" in residual:
            token = next(part for part in residual.split() if part.startswith("--hash"))
            raise ValueError(
                f"{path}:{number}: unexpected token {token!r}; only --hash=sha256:<64 lowercase hex> allowed"
            )
        match = _REQ_RE.match(re.sub(r"\s+", " ", residual))
        if match is None:
            raise ValueError(
                f"{path}:{number}: requirement must be exactly pinned as name==version: {residual.split()[0]!r}"
            )
        if not hashes:
            raise ValueError(f"{path}:{number}: {match.group('name')} has no --hash=sha256 artifact digest")
        if len(set(hashes)) != len(hashes):
            raise ValueError(f"{path}:{number}: duplicate hashes for {match.group('name')}")
        entry = LockedRequirement(
            name=match.group("name"),
            version=match.group("version"),
            hashes=tuple(sorted(hashes)),
            marker=(match.group("marker") or "").strip() or None,
        )
        if entry.normalized_name in seen:
            raise ValueError(
                f"{path}:{number}: duplicate distribution {entry.name} (first at line {seen[entry.normalized_name]})"
            )
        seen[entry.normalized_name] = number
        entries.append(entry)
    if not entries:
        raise ValueError(f"{path}: lock file contains no requirements")
    return sorted(entries, key=lambda entry: entry.normalized_name)


def parse_lock_header(path: Path) -> dict[str, str]:
    """Read the leading `# key: value` metadata block written by the generator."""
    header: dict[str, str] = {}
    for raw in path.read_text().splitlines():
        stripped = raw.strip()
        if not stripped:
            continue
        if not stripped.startswith("#"):
            break
        match = _HEADER_RE.match(stripped)
        if match:
            header[match.group("key")] = match.group("value")
    return header
